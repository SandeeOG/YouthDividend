  const leg = (name, color, kind = 'dot') => ({ name, color, kind });
  const S = D; // shorthand
  const EUROSTAT_GEO = 'EU Member States plus EFTA and EU candidate countries reporting to Eurostat';

  /* 1 — The Age of Independence ------------------------------------------------ */
